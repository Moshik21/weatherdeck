#!/bin/sh
# Wraps fixture.json as fixture.js so index.html also works when opened from file://
# (browsers refuse fetch() of local files). The data is the same bytes.
cd "$(dirname "$0")" || exit 1
{
  printf '// Generated by make-fixture-js.sh from fixture.json. Do not edit by hand.\n'
  printf 'window.WEATHERDECK_FIXTURE = '
  cat fixture.json
  printf ';\n'
} > fixture.js
